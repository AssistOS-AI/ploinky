// Local exclusion policy for skill exports.
//
// Shared by value like the export transaction protocol: Ploinky keeps this
// file at cli/utils/skills/exportExclusions.mjs and Explorer a byte-identical
// copy at explorer/utils/server/skill-export-exclusions.mjs. Only Node
// built-ins may be imported.
//
// Git targets never receive tracked `.gitignore` writes or rules in the shared
// `info/exclude`. The worktree's private config points `core.excludesFile` at
// a Ploinky-managed file inside that worktree's private Git directory. Git
// reads exactly one effective excludes file, so a live external excludes
// policy is never shadowed unless this invocation authorizes composition.
// Non-git folders may keep a managed `.gitignore` block backed by a receipt.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';

export const IGNORE_MARKER_START = '# >>> ploinky default-skills >>>';
export const IGNORE_MARKER_END = '# <<< ploinky default-skills <<<';
export const IGNORE_RECEIPT = path.join('.agents', '.ploinky-ignore-receipt.json');
export const MANAGED_EXCLUDES = 'ploinky-skill-exports.exclude';
export const COMPOSITION_RECORD = 'ploinky-skill-exports.exclusions.json';
export const GIT_CONFIG_LOCK = 'ploinky-skill-exports-config.lock';
const RECORD_PROTOCOL = 'ploinky-skill-exclusions';
const MANAGED_HEADER = '# Generated by Ploinky for skill exports in this worktree only.\n# Editing this file hands control back to you; Ploinky then leaves it unchanged.\n';

const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

// ---------------------------------------------------------------------------
// Git access.

const GIT_ENVIRONMENT_OVERRIDES = ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR', 'GIT_OBJECT_DIRECTORY', 'GIT_PREFIX'];

export function runGit(args, { cwd, input, env = process.env } = {}) {
    const environment = { ...env, GIT_OPTIONAL_LOCKS: '0', LC_ALL: 'C', GIT_TERMINAL_PROMPT: '0' };
    for (const name of GIT_ENVIRONMENT_OVERRIDES) delete environment[name];
    const result = spawnSync('git', ['-c', 'core.fsmonitor=false', '-c', 'core.hooksPath=/dev/null', ...args], { cwd, input, env: environment, encoding: 'buffer', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
    if (result.error) throw result.error;
    return { status: result.status, stdout: result.stdout, stderr: result.stderr.toString('utf8') };
}

const text = result => result.stdout.toString('utf8');

function ancestorHasGitEntry(root) {
    for (let directory = root; ; directory = path.dirname(directory)) {
        if (fs.lstatSync(path.join(directory, '.git'), { throwIfNoEntry: false })) return true;
        if (path.dirname(directory) === directory) return false;
    }
}

// Identity of the Git worktree containing `folder`, or null outside Git.
// Only a positive "not a git repository" with no `.git` entry above the
// target counts as outside Git; every other failure (safe.directory refusal,
// discovery limits, a damaged `.git`, no git binary) is `unavailable`.
export function resolveGitIdentity(folder, { git = runGit } = {}) {
    const root = fs.realpathSync(folder);
    let probe;
    try { probe = git(['rev-parse', '--is-inside-work-tree'], { cwd: root }); } catch (error) {
        return { root, unavailable: true, reason: `git could not run: ${error.code || error.message}` };
    }
    if (probe.status !== 0) {
        if (/not a git repository/i.test(probe.stderr) && !ancestorHasGitEntry(root)) return null;
        return { root, unavailable: true, reason: probe.stderr.trim() || `git rev-parse exited with ${probe.status}` };
    }
    if (text(probe).trim() !== 'true') return { root, insideWorkTree: false };
    const fields = git(['rev-parse', '--path-format=absolute', '--show-toplevel', '--absolute-git-dir', '--git-common-dir', '--git-path', 'config.worktree'], { cwd: root });
    if (fields.status !== 0) throw new Error(`git rev-parse failed in ${root}: ${fields.stderr.trim()}`);
    const [topLevel, gitDir, commonDir, worktreeConfig] = text(fields).split('\n').map(value => value.trim());
    const canonical = value => { try { return fs.realpathSync(value); } catch (_) { return path.resolve(value); } };
    const identity = {
        root,
        insideWorkTree: true,
        topLevel: canonical(topLevel),
        gitDir: canonical(gitDir),
        commonDir: canonical(commonDir),
        worktreeConfig: path.join(canonical(path.dirname(worktreeConfig)), path.basename(worktreeConfig)),
    };
    identity.linked = identity.gitDir !== identity.commonDir;
    identity.relative = path.relative(identity.topLevel, root).split(path.sep).filter(Boolean).join('/');
    return identity;
}

// Literal gitignore pattern anchored at the top level. Every wildcard,
// bracket, backslash and trailing space is escaped; links have no slash.
export function escapeIgnorePattern(relative) {
    if (/[\n\r]/.test(relative)) return null;
    let escaped = relative.split('/').map(part => part.replace(/[\\*?[\]]/g, match => `\\${match}`)).join('/');
    escaped = escaped.replace(/ +$/, spaces => spaces.replace(/ /g, '\\ '));
    return `/${escaped}`;
}

function configValues(file, key, git, cwd) {
    if (!fs.existsSync(file)) return [];
    const result = git(['config', '--file', file, '--get-all', key], { cwd });
    if (result.status === 1) return [];
    if (result.status !== 0) throw new Error(`git config --file ${file} failed: ${result.stderr.trim()}`);
    return text(result).split('\n').filter(value => value !== '');
}

function readRegular(file) {
    const stat = fs.lstatSync(file, { throwIfNoEntry: false });
    if (!stat || !stat.isFile()) return null;
    return fs.readFileSync(file);
}

function expandPath(value, base, env) {
    if (value === '~' || value.startsWith('~/')) return path.join(env.HOME || os.homedir(), value.slice(1));
    return path.isAbsolute(value) ? value : path.resolve(base, value);
}

function trustedHostConfigOrigin(scope, origin, env) {
    if (scope === 'default') return true;
    if (!origin.startsWith('file:')) return false;
    const canonical = file => { try { return fs.realpathSync(file); } catch (_) { return path.resolve(file); } };
    const home = env.HOME || os.homedir();
    const expected = scope === 'global'
        ? (env.GIT_CONFIG_GLOBAL ? [env.GIT_CONFIG_GLOBAL] : [path.join(home, '.gitconfig'), path.join(env.XDG_CONFIG_HOME || path.join(home, '.config'), 'git', 'config')])
        : scope === 'system' ? [env.GIT_CONFIG_SYSTEM || '/etc/gitconfig'] : [];
    return expected.some(file => canonical(file) === canonical(origin.slice('file:'.length)));
}

// The excludes file Git would use here without a worktree-scope value.
// An unreadable policy still exists: treating it as absent would hide it
// behind our private file. The host also must not copy content selected by
// repository-local config outside the selected workspace.
export function inheritedExcludes(identity, { git = runGit, env = process.env, gitDirBoundary = null, authorizeComposition = false } = {}) {
    const result = git(['config', '--show-scope', '--show-origin', '-z', '--get-all', 'core.excludesFile'], { cwd: identity.root, env });
    const entries = [];
    if (result.status === 0) {
        const parts = text(result).split('\0');
        for (let index = 0; index + 2 < parts.length; index += 3) entries.push({ scope: parts[index], origin: parts[index + 1], value: parts[index + 2] });
    }
    if (result.status !== 0 && result.status !== 1) throw new Error(`Git could not identify the inherited excludes policy: ${result.stderr.trim()}`);
    const inherited = entries.filter(entry => entry.scope !== 'worktree' && entry.scope !== 'command').pop();
    let file;
    let scope;
    let origin;
    if (inherited) {
        file = expandPath(inherited.value, identity.topLevel, env);
        scope = inherited.scope;
        origin = inherited.origin;
    } else {
        const xdg = env.XDG_CONFIG_HOME;
        file = xdg ? path.join(xdg, 'git', 'ignore') : path.join(env.HOME || os.homedir(), '.config', 'git', 'ignore');
        scope = 'default';
        origin = xdg ? 'XDG_CONFIG_HOME' : 'HOME';
    }
    const policy = { scope, origin, path: file, digest: null, bytes: null, live: true };
    const unavailable = (code, reason) => ({ ...policy, unavailable: { code, reason } });
    const repositorySelected = !['global', 'system', 'default'].includes(scope);
    if (gitDirBoundary && repositorySelected && !insideBoundary(gitDirBoundary, path.resolve(file))) {
        return unavailable('exclusions-source-outside-boundary', `The repository-selected excludes file ${file} is outside ${gitDirBoundary}; the host will not read or compose it.`);
    }
    if (gitDirBoundary && !repositorySelected && !trustedHostConfigOrigin(scope, origin, env)) {
        return unavailable('exclusions-origin-unverified', `The inherited excludes policy comes from an included or unverified ${scope} configuration (${origin}); it is left unchanged.`);
    }
    let descriptor;
    try {
        const entry = fs.lstatSync(file, { throwIfNoEntry: false });
        if (!entry) return { ...policy, live: false };
        const resolved = fs.realpathSync(file);
        if (gitDirBoundary && repositorySelected && !insideBoundary(gitDirBoundary, resolved)) {
            return unavailable('exclusions-source-outside-boundary', `The repository-selected excludes file ${file} resolves outside ${gitDirBoundary}; the host will not read or compose it.`);
        }
        // Even a valid host policy needs consent on this invocation. A
        // workspace-writable receipt cannot grant access to host file bytes.
        if (gitDirBoundary && !authorizeComposition) return policy;
        const stat = fs.statSync(resolved);
        if (!stat.isFile()) return unavailable('exclusions-source-unavailable', `The inherited excludes file ${file} is not a regular file; it is left unchanged.`);
        descriptor = fs.openSync(resolved, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
        if (!fs.fstatSync(descriptor).isFile()) return unavailable('exclusions-source-unavailable', `The inherited excludes file ${file} is not a regular file; it is left unchanged.`);
        const bytes = fs.readFileSync(descriptor);
        return { ...policy, digest: sha256(bytes), bytes, live: Boolean(bytes.toString('utf8').trim()) };
    } catch (error) {
        return unavailable('exclusions-source-unavailable', `The inherited excludes file ${file} could not be verified (${error.code || error.message}); it is left unchanged.`);
    } finally {
        if (descriptor !== undefined) fs.closeSync(descriptor);
    }
}

// One disposable fixture per process proves that this Git keeps worktree
// config private to its worktree once extensions.worktreeConfig is enabled.
let capabilityCache = null;
export function worktreeConfigCapability({ git = runGit } = {}) {
    if (capabilityCache) return capabilityCache;
    const base = fs.mkdtempSync(path.join(os.tmpdir(), 'ploinky-worktree-config-'));
    const env = { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: path.join(base, 'global') };
    fs.writeFileSync(env.GIT_CONFIG_GLOBAL, '');
    const run = (args, cwd) => {
        const result = git(args, { cwd, env });
        if (result.status !== 0) throw new Error(result.stderr.trim());
        return text(result).trim();
    };
    try {
        const main = path.join(base, 'main');
        fs.mkdirSync(main);
        run(['init', '-q'], main);
        run(['-c', 'user.name=probe', '-c', 'user.email=probe@invalid', 'commit', '-q', '--allow-empty', '-m', 'probe'], main);
        run(['worktree', 'add', '-q', '-b', 'probe', path.join(base, 'linked')], main);
        run(['config', 'extensions.worktreeConfig', 'true'], main);
        const linked = path.join(base, 'linked');
        const file = run(['rev-parse', '--path-format=absolute', '--git-path', 'config.worktree'], linked);
        run(['config', '--file', file, 'core.excludesFile', '/probe'], linked);
        const origin = git(['config', '--show-origin', '--get', 'core.excludesFile'], { cwd: linked, env });
        const mainValue = git(['config', '--get', 'core.excludesFile'], { cwd: main, env });
        const ok = origin.status === 0 && text(origin).includes('config.worktree') && text(origin).trim().endsWith('/probe') && mainValue.status === 1;
        capabilityCache = ok ? { supported: true } : { supported: false, reason: 'worktree config was not private in a disposable fixture' };
    } catch (error) {
        capabilityCache = { supported: false, reason: error.message };
    } finally {
        fs.rmSync(base, { recursive: true, force: true });
    }
    return capabilityCache;
}

// ---------------------------------------------------------------------------
// Non-git managed block.

export function managedBlock(patterns) {
    return `${IGNORE_MARKER_START}\n${patterns.join('\n')}\n${IGNORE_MARKER_END}\n`;
}

function readReceipt(root) {
    try {
        const bytes = readRegular(path.join(root, IGNORE_RECEIPT));
        if (!bytes) return null;
        const receipt = JSON.parse(bytes.toString('utf8'));
        if (receipt?.protocol !== RECORD_PROTOCOL || receipt.path !== '.gitignore' || typeof receipt.block !== 'string' || typeof receipt.after !== 'string') return null;
        return receipt;
    } catch (_) {
        return null;
    }
}

const receiptBytes = receipt => `${JSON.stringify(receipt, null, 2)}\n`;

// Current bytes with the receipt's exact block removed, or null when the
// block is not present exactly once.
function withoutReceiptBlock(bytes, receipt) {
    const content = bytes.toString('utf8');
    const first = content.indexOf(receipt.block);
    if (first < 0 || content.indexOf(receipt.block, first + 1) >= 0) return null;
    return Buffer.from(content.slice(0, first) + content.slice(first + receipt.block.length));
}

function planNonGit(root, patterns, options) {
    const gitignore = path.join(root, '.gitignore');
    const stat = fs.lstatSync(gitignore, { throwIfNoEntry: false });
    if (stat && !stat.isFile()) return { outcome: { status: 'preserved', mode: 'non-git', code: 'gitignore-not-regular-file', reason: `${gitignore} is not a regular file; it is left unchanged.` }, artifacts: [] };
    const current = stat ? fs.readFileSync(gitignore) : null;
    const receipt = readReceipt(root);
    const block = managedBlock(patterns);
    const hasMarkers = current !== null && current.toString('utf8').includes(IGNORE_MARKER_START);
    let base;
    if (hasMarkers) {
        if (!receipt || sha256(current) !== receipt.after) {
            return { outcome: { status: 'preserved', mode: 'non-git', code: 'unverified-ignore-block-preserved', reason: `${gitignore} has a Ploinky marker block without a matching write receipt; it is left unchanged. Remove the block by hand to let Ploinky manage it again.` }, artifacts: [] };
        }
        base = withoutReceiptBlock(current, receipt);
        if (base === null) return { outcome: { status: 'preserved', mode: 'non-git', code: 'unverified-ignore-block-preserved', reason: `${gitignore} no longer contains the recorded block exactly once.` }, artifacts: [] };
    } else {
        if (!options.nonGitBlock) return { outcome: { status: 'unchanged', mode: 'non-git' }, artifacts: [] };
        base = current ?? Buffer.alloc(0);
    }
    const prefix = base.length && !base.toString('utf8').endsWith('\n') ? '\n' : '';
    const next = Buffer.from(base.toString('utf8') + prefix + block);
    if (current !== null && next.equals(current)) return { outcome: { status: 'unchanged', mode: 'non-git' }, artifacts: [] };
    const beforeAbsent = hasMarkers ? Boolean(receipt.beforeAbsent) : current === null;
    const nextReceipt = {
        protocol: RECORD_PROTOCOL, version: 1, path: '.gitignore',
        before: beforeAbsent ? null : sha256(base), beforeAbsent,
        after: sha256(next), block: prefix + block,
    };
    return {
        outcome: { status: 'published', mode: 'non-git' },
        artifacts: [
            { kind: 'gitignore', bytes: next },
            { kind: 'receipt', bytes: Buffer.from(receiptBytes(nextReceipt)) },
        ],
    };
}

