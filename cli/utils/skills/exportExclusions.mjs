// Git private excludes.

function readRecord(file) {
    try {
        const bytes = readRegular(file);
        if (!bytes) return null;
        const record = JSON.parse(bytes.toString('utf8'));
        return record?.protocol === RECORD_PROTOCOL ? record : null;
    } catch (_) {
        return null;
    }
}

function writable(target) {
    try { fs.accessSync(target, fs.constants.W_OK); return true; } catch (_) { return false; }
}

function deferred(code, reason, extra = {}) {
    return { outcome: { status: 'deferred', mode: 'git', code, reason, ...extra }, artifacts: [] };
}

function broadRules(identity, git) {
    const probe = [identity.relative, '.agents', 'skills', '.ploinky-visibility-probe'].filter(Boolean).join('/');
    const result = git(['check-ignore', '-v', '--no-index', '--', probe], { cwd: identity.topLevel });
    if (result.status !== 0) return [];
    const line = text(result).split('\n')[0];
    const match = /^(.*?):(\d+):(.*)\t/.exec(line);
    if (!match) return [];
    const source = path.resolve(identity.topLevel, match[1]);
    if (source === path.join(identity.gitDir, MANAGED_EXCLUDES)) return [];
    return [{ source: match[1], line: Number(match[2]), pattern: match[3] }];
}

// Undo a previous non-git block after the folder became a Git worktree. Only
// an untracked file whose bytes match the receipt is changed.
function planGitInitMigration(identity, git) {
    const receipt = readReceipt(identity.root);
    if (!receipt) return { artifacts: [], warnings: [] };
    const gitignore = path.join(identity.root, '.gitignore');
    const current = readRegular(gitignore);
    if (!current || sha256(current) !== receipt.after) return { artifacts: [], warnings: [] };
    const tracked = git(['ls-files', '--error-unmatch', '--', '.gitignore'], { cwd: identity.root }).status === 0;
    if (tracked) {
        return { artifacts: [], warnings: [{ code: 'unverified-ignore-block-preserved', reason: `${gitignore} is tracked with a Ploinky block; it is repository policy now and is left unchanged.` }] };
    }
    const base = withoutReceiptBlock(current, receipt);
    if (base === null || (receipt.before !== null && sha256(base) !== receipt.before)) return { artifacts: [], warnings: [] };
    return {
        artifacts: [
            { kind: 'gitignore', bytes: receipt.beforeAbsent && base.length === 0 ? null : base },
            { kind: 'receipt', bytes: null },
        ],
        warnings: [],
    };
}

function insideBoundary(boundary, candidate) {
    const relative = path.relative(boundary, candidate);
    return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
}

// Containers see their own HOME, XDG and global Git configuration, not the
// repository owner's, so they cannot prove which excludes policy is live.
export function detectContainerExecutor() {
    return ['/run/.containerenv', '/.dockerenv'].some(marker => { try { return fs.existsSync(marker); } catch (_) { return false; } });
}

// Resolve less-trusted metadata without asking Git to load its configuration.
// This runs before lock discovery as well as before every host publication.
function assertHostGitBoundary(root, boundary) {
    const reject = (code, reason) => {
        const error = new Error(reason);
        error.code = 'SKILL_EXPORT_HOST_BOUNDARY';
        error.exclusionCode = code;
        throw error;
    };
    const inspect = (candidate, directory = false) => {
        const absolute = path.resolve(candidate);
        if (!insideBoundary(boundary, absolute)) reject('git-directory-outside-boundary', `Git metadata resolves outside ${boundary}; nothing is written.`);
        let current = boundary;
        const parts = path.relative(boundary, absolute).split(path.sep).filter(Boolean);
        for (let index = 0; index < parts.length; index++) {
            current = path.join(current, parts[index]);
            const stat = fs.lstatSync(current, { throwIfNoEntry: false });
            if (!stat) return null;
            const needsDirectory = index < parts.length - 1 || directory;
            if (stat.isSymbolicLink() || (needsDirectory ? !stat.isDirectory() : !stat.isFile() || stat.nlink !== 1)) {
                reject('git-metadata-not-private-regular', `Git metadata is linked or not a private regular path: ${current}; nothing is written.`);
            }
        }
        return absolute;
    };
    const read = filename => {
        inspect(filename);
        const fd = fs.openSync(filename, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
        try {
            const stat = fs.fstatSync(fd);
            if (!stat.isFile() || stat.nlink !== 1 || stat.size > 1024 * 1024) reject('git-metadata-not-private-regular', `Git metadata is not a bounded private file: ${filename}`);
            return fs.readFileSync(fd, 'utf8');
        } finally { fs.closeSync(fd); }
    };
    inspect(root, true);
    let top = root;
    for (;;) {
        const entry = path.join(top, '.git');
        const stat = fs.lstatSync(entry, { throwIfNoEntry: false });
        if (stat) {
            let gitDir;
            if (stat.isDirectory()) gitDir = entry;
            else {
                const match = /^gitdir: ([^\r\n]+)\r?\n?$/.exec(read(entry));
                if (!match) reject('git-metadata-invalid', `Git metadata pointer is invalid: ${entry}`);
                gitDir = path.resolve(top, match[1]);
            }
            inspect(gitDir, true);
            const commonFile = path.join(gitDir, 'commondir');
            const commonDir = fs.lstatSync(commonFile, { throwIfNoEntry: false })
                ? path.resolve(gitDir, read(commonFile).trim()) : gitDir;
            inspect(commonDir, true);
            for (const file of new Set([path.join(commonDir, 'config'), path.join(commonDir, 'config.worktree'), path.join(gitDir, 'config.worktree')])) {
                if (inspect(file) && /^\s*\[\s*include(?:if)?\b/im.test(read(file))) reject('git-config-include-unverified', `Repository Git includes cannot be used by host exclusion refresh: ${file}`);
            }
            for (const file of [MANAGED_EXCLUDES, COMPOSITION_RECORD]) inspect(path.join(gitDir, file));
            return;
        }
        if (top === boundary) return;
        top = path.dirname(top);
    }
}

function planGit(identity, patterns, options) {
    const { git, env } = options;
    if (identity.unavailable) return deferred('git-identity-unavailable', `Git could not identify the repository containing ${identity.root} (${identity.reason}); nothing is written and no .gitignore is created.`);
    if (!identity.insideWorkTree) return deferred('git-target-unsupported', `${identity.root} is inside a Git directory, not a worktree.`);
    if (options.containerExecutor) return deferred('exclusions-executor-view-unverified', `This process runs in a container or agent sandbox whose HOME, XDG and global Git configuration can differ from the repository owner's, so it cannot prove which excludes policy is live. Private exclusions for ${identity.topLevel} are left unchanged; run the operation from the host to refresh them.`);
    // A caller that received the folder from less trusted content (the host
    // refreshing Box-reported folders) confines Git metadata to its boundary:
    // a planted `.git` file must not redirect writes outside it.
    if (options.gitDirBoundary && ![identity.topLevel, identity.gitDir, identity.commonDir].every(dir => insideBoundary(options.gitDirBoundary, dir))) {
        return deferred('git-directory-outside-boundary', `The Git metadata for ${identity.root} resolves outside ${options.gitDirBoundary}; nothing is written.`);
    }
    if (!options.heldGitLocks.includes(identity.commonDir)) return deferred('git-metadata-lock-missing', `The common Git configuration lock for ${identity.commonDir} is not held; exclusions are deferred.`);
    const capability = options.capability({ git });
    if (!capability.supported) return deferred('git-worktree-config-unsupported', `This Git cannot keep worktree configuration private (${capability.reason}); no shared rules are written.`);
    const commonConfig = path.join(identity.commonDir, 'config');
    const mainWorktreeConfig = path.join(identity.commonDir, 'config.worktree');
    const managedFile = path.join(identity.gitDir, MANAGED_EXCLUDES);
    const recordFile = path.join(identity.gitDir, COMPOSITION_RECORD);
    const cwd = identity.root;
    for (const file of new Set([commonConfig, mainWorktreeConfig, identity.worktreeConfig])) {
        const nativeLock = `${file}.lock`;
        if (fs.lstatSync(nativeLock, { throwIfNoEntry: false })) {
            return deferred('git-config-busy', `Git configuration has an existing lock at ${nativeLock}; it is preserved and exclusions are deferred.`);
        }
    }
    const values = (file, key) => configValues(file, key, git, cwd);
    for (const target of [commonConfig, identity.gitDir, identity.commonDir, ...[identity.worktreeConfig, managedFile, recordFile].filter(fs.existsSync)]) {
        if (!writable(target)) return deferred('git-config-read-only', `${target} is not writable; exclusions are deferred and nothing is changed.`);
    }
    const extension = values(commonConfig, 'extensions.worktreeConfig');
    const enabled = extension.length > 0 && ['true', 'yes', 'on', '1'].includes(extension[extension.length - 1].toLowerCase());
    if (extension.length && !enabled) return deferred('worktree-config-disabled', `extensions.worktreeConfig is explicitly '${extension.at(-1)}' in ${commonConfig}; it is left unchanged.`);

    const artifacts = [];
    const migrationUnsets = [];
    if (!enabled) {
        // Documented migration: the main worktree's core.worktree, and
        // core.bare=true, move to its config.worktree before other worktrees
        // stop inheriting them. Enabled first, unset last.
        for (const key of ['core.worktree', 'core.bare']) {
            const common = values(commonConfig, key);
            if (!common.length || (key === 'core.bare' && common.at(-1).toLowerCase() !== 'true')) continue;
            const existing = values(mainWorktreeConfig, key);
            if (existing.length && existing.at(-1) !== common.at(-1)) return deferred('worktree-config-migration-conflict', `${key} differs between ${commonConfig} and ${mainWorktreeConfig}; resolve it before enabling extensions.worktreeConfig.`);
            if (!existing.length) artifacts.push({ kind: 'git-config', file: mainWorktreeConfig, key, before: [], after: [common.at(-1)] });
            migrationUnsets.push({ kind: 'git-config', file: commonConfig, key, before: common, after: [] });
        }
        artifacts.push({ kind: 'git-config', file: commonConfig, key: 'extensions.worktreeConfig', before: extension, after: ['true'] });
        artifacts.push(...migrationUnsets);
    }

    const current = values(identity.worktreeConfig, 'core.excludesFile');
    const record = readRecord(recordFile);
    // A relocated worktree still carries our record next to the managed file;
    // the stale absolute path is re-resolved rather than treated as foreign.
    const relocated = current.length === 1 && current[0] !== managedFile && record?.excludesFile === current[0]
        && path.basename(current[0]) === MANAGED_EXCLUDES;
    const managed = current.length === 1 && (current[0] === managedFile || relocated);
    if (current.length && !managed) {
        return { outcome: { status: 'relinquished', mode: 'git', code: 'worktree-excludes-user-managed', reason: `core.excludesFile in ${identity.worktreeConfig} is set by someone else; it is left unchanged.` }, artifacts: [] };
    }
    if (managed) {
        const bytes = readRegular(managedFile);
        if (!record || (record.excludesFile !== managedFile && !relocated) || !bytes || sha256(bytes) !== record.composedDigest) {
            return { outcome: { status: 'relinquished', mode: 'git', code: 'managed-excludes-edited', reason: `${managedFile} or its record changed outside Ploinky; the edit is preserved and Ploinky no longer updates it.` }, artifacts: [] };
        }
    }
    const inherited = inheritedExcludes(identity, { git, env, gitDirBoundary: options.gitDirBoundary, authorizeComposition: options.authorizeComposition });
    const authorized = options.authorizeComposition === true;
    if (inherited.unavailable || (inherited.live && !authorized)) {
        const code = inherited.unavailable?.code || 'exclusions-deferred';
        const reason = inherited.unavailable?.reason || `The effective excludes file ${inherited.path} (${inherited.scope}) would be shadowed by a private worktree excludes file. It is left unchanged, so generated skill links may show as untracked. Set PLOINKY_SKILL_EXCLUDES_COMPOSE=1 for each invocation that may compose it into a private file (later edits to ${inherited.path} are picked up on the next authorized update, not live).`;
        if (managed) {
            // Hand the shadowed policy back: restore the absent key only while it is still ours.
            return { outcome: { status: 'deferred', mode: 'git', code, reason, relinquished: true }, artifacts: [{ kind: 'git-config', file: identity.worktreeConfig, key: 'core.excludesFile', before: current, after: [] }] };
        }
        return deferred(code, reason);
    }
    const composed = Buffer.from(MANAGED_HEADER + patterns.join('\n') + '\n'
        + (inherited.live ? `\n# Previously effective excludes: ${inherited.path}\n${inherited.bytes.toString('utf8')}${inherited.bytes.toString('utf8').endsWith('\n') ? '' : '\n'}` : ''));
    const rules = broadRules(identity, git);
    const warnedBefore = new Set((record?.broadRules || []).map(rule => JSON.stringify(rule)));
    const warnings = rules.filter(rule => !warnedBefore.has(JSON.stringify(rule))).map(rule => ({
        code: 'broad-ignore-rule', reason: `Ignore rule '${rule.pattern}' in ${rule.source}:${rule.line} hides every file under .agents/skills; locally authored skills there stay hidden.`, rule,
    }));
    const migration = planGitInitMigration(identity, git);
    warnings.push(...migration.warnings);
    const nextRecord = {
        protocol: RECORD_PROTOCOL, version: 1,
        excludesFile: managedFile, configFile: identity.worktreeConfig,
        previous: record?.previous ?? { present: current.length > 0 && !managed, values: managed ? [] : current },
        inherited: { scope: inherited.scope, origin: inherited.origin, path: inherited.path, digest: inherited.digest },
        authorized,
        composedDigest: sha256(composed),
        configFingerprint: sha256(JSON.stringify([identity.worktreeConfig, managedFile, 'true'])),
        broadRules: rules,
    };
    artifacts.push({ kind: 'private-file', path: managedFile, bytes: composed });
    artifacts.push({ kind: 'private-file', path: recordFile, bytes: Buffer.from(`${JSON.stringify(nextRecord, null, 2)}\n`) });
    if (!managed || relocated) artifacts.push({ kind: 'git-config', file: identity.worktreeConfig, key: 'core.excludesFile', before: current, after: [managedFile] });
    artifacts.push(...migration.artifacts);
    return {
        outcome: { status: 'published', mode: 'git', composed: inherited.live, warnings },
        artifacts,
        state: { mode: 'git', identity, previous: nextRecord.previous, inherited: nextRecord.inherited, sourceDigest: inherited.digest, composedDigest: nextRecord.composedDigest, configFingerprint: nextRecord.configFingerprint },
    };
}

/** Planner used by the export transaction. `ownedPaths` are root-relative
 * paths of verified owned output, computed by the transaction under its
 * locks; nothing here infers ownership from names or link targets.
 */
export function createSkillExclusionPlanner({ authorizeComposition = false, nonGitBlock = false, git = runGit, env = process.env, capability = worktreeConfigCapability, containerExecutor = detectContainerExecutor(), gitDirBoundary = null } = {}) {
    const boundary = gitDirBoundary ? fs.realpathSync(gitDirBoundary) : null;
    return {
        hostBoundary: boundary,
        assertSafeTarget(folder) {
            if (boundary) assertHostGitBoundary(path.resolve(folder), boundary);
        },
        commonDir(folder) {
            this.assertSafeTarget(folder);
            try { const identity = resolveGitIdentity(folder, { git }); return identity?.insideWorkTree ? identity.commonDir : null; } catch (_) { return null; }
        },
        plan(input) {
            try {
                return this.planUnchecked(input);
            } catch (error) {
                // Exclusions never abort the export itself.
                return { outcome: { status: 'deferred', mode: 'unknown', code: 'exclusions-planning-failed', reason: `Local exclusions could not be planned: ${error.message}` }, artifacts: [], state: { mode: 'unknown', identity: null } };
            }
        },
        planUnchecked({ root, ownedPaths, heldGitLocks = [] }) {
            this.assertSafeTarget(root);
            const identity = resolveGitIdentity(root, { git });
            const prefix = identity?.insideWorkTree ? identity.relative : '';
            const patterns = [];
            const unrepresentable = [];
            for (const relative of [...new Set(ownedPaths)].sort()) {
                const pattern = escapeIgnorePattern([prefix, relative].filter(Boolean).join('/'));
                if (pattern) patterns.push(pattern); else unrepresentable.push(relative);
            }
            const planned = identity
                ? planGit(identity, patterns, { git, env, authorizeComposition, capability, heldGitLocks, containerExecutor, gitDirBoundary: boundary })
                : planNonGit(root, patterns, { nonGitBlock });
            if (unrepresentable.length) planned.outcome.unrepresentable = unrepresentable;
            // The folder lets a host process act on a deferral from a container.
            planned.outcome.folder = root;
            planned.state ||= { mode: identity ? 'git' : 'non-git', identity: identity || null };
            return planned;
        },
    };
}

// ---------------------------------------------------------------------------
// Pre-pull assessment.

function statusEntries(repoPath, git) {
    const tracked = git(['status', '--porcelain=v1', '-z', '--untracked-files=no'], { cwd: repoPath });
    if (tracked.status !== 0) throw new Error(`git status failed in ${repoPath}: ${tracked.stderr.trim()}`);
    const entries = [];
    const parts = text(tracked).split('\0');
    for (let index = 0; index < parts.length; index++) {
        const item = parts[index];
        if (item.length < 4) continue;
        const code = item.slice(0, 2);
        entries.push({ code, path: item.slice(3) });
        if (code[0] === 'R' || code[0] === 'C') index++;
    }
    const untracked = git(['ls-files', '-z', '--others', '--exclude-standard', '--', ':(glob).gitignore', ':(glob)**/.gitignore'], { cwd: repoPath });
    if (untracked.status === 0) for (const item of text(untracked).split('\0').filter(Boolean)) entries.push({ code: '??', path: item });
    return entries;
}

/** Called before a verified Git update classifies a checkout as dirty.
 * Restores a `.gitignore` only when an exact write receipt matches both its
 * current bytes and the index; everything else is preserved and reported.
 */
export function assessGeneratedIgnoreState({ repoPath, git = runGit } = {}) {
    const identity = resolveGitIdentity(repoPath, { git });
    if (!identity?.insideWorkTree) return { status: 'none' };
    const top = identity.topLevel;
    const candidates = statusEntries(top, git).filter(entry => path.posix.basename(entry.path) === '.gitignore');
    const restored = [];
    const preserved = [];
    for (const entry of candidates) {
        const file = path.join(top, entry.path);
        const current = readRegular(file);
        if (!current || !current.toString('utf8').includes(IGNORE_MARKER_START)) continue;
        const preserve = (code, reason) => preserved.push({ path: entry.path, code, reason });
        const [staged, worktree] = entry.code;
        if (staged === 'U' || worktree === 'U' || entry.code === 'AA' || entry.code === 'DD') { preserve('ignore-file-conflicted', `${entry.path} is conflicted; resolve the conflict before updating.`); continue; }
        if (entry.code !== '??' && staged !== ' ') { preserve('staged-ignore-change-preserved', `${entry.path} has staged changes; commit or unstage them before updating.`); continue; }
        const receipt = readReceipt(path.dirname(file));
        if (!receipt || sha256(current) !== receipt.after) {
            preserve('unverified-ignore-block-preserved', `${entry.path} contains a Ploinky marker block with no matching write receipt, so it may hold your edits. Inspect it, then commit it or restore it with 'git restore -- ${entry.path}' before updating.`);
            continue;
        }
        const base = withoutReceiptBlock(current, receipt);
        if (base === null || (receipt.before !== null && sha256(base) !== receipt.before)) { preserve('unverified-ignore-block-preserved', `${entry.path} no longer matches its write receipt.`); continue; }
        let target;
        if (entry.code === '??') {
            if (!receipt.beforeAbsent || base.length) { preserve('unverified-ignore-block-preserved', `${entry.path} is untracked and holds content Ploinky did not write.`); continue; }
            target = null;
        } else {
            const index = git(['show', `:0:${entry.path}`], { cwd: top });
            if (index.status !== 0 || !index.stdout.equals(base)) { preserve('unverified-ignore-block-preserved', `${entry.path} differs from the index beyond the recorded Ploinky block.`); continue; }
            target = index.stdout;
        }
        // Compare before write: the bytes must still be the receipt's bytes.
        const temporary = `${file}.${crypto.randomUUID()}.tmp`;
        try {
            if (target !== null) fs.writeFileSync(temporary, target, { flag: 'wx', mode: fs.statSync(file).mode & 0o777 });
            const again = readRegular(file);
            if (!again || !again.equals(current)) { preserve('unverified-ignore-block-preserved', `${entry.path} changed during assessment.`); continue; }
            if (target === null) fs.unlinkSync(file); else fs.renameSync(temporary, file);
        } finally {
            fs.rmSync(temporary, { force: true });
        }
        fs.rmSync(path.join(path.dirname(file), IGNORE_RECEIPT), { force: true });
        restored.push(entry.path);
    }
    if (preserved.length) return { status: 'preserve', code: preserved[0].code, reason: preserved.map(item => item.reason).join(' '), paths: preserved.map(item => item.path), preserved, restored };
    if (restored.length) return { status: 'restored', paths: restored };
    return { status: 'none' };
}
